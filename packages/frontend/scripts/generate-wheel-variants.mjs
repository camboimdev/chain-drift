/**
 * Procedural wheel rim generator for Chain Drift.
 *
 * Run: node scripts/generate-wheel-variants.mjs
 *
 * Outputs OBJ files into public/parts/:
 *   Car_Wheels_5Spoke.obj
 *   Car_Wheels_Turbine.obj
 *   Car_Wheels_Mesh.obj
 *
 * Geometry is derived from the original Car_Wheels.obj measurements:
 *   - Wheel radius      : 0.40 units
 *   - Wheel center Y    : 0.40 (bottom of tire touches Y=0)
 *   - Wheel half-width  : 0.10 (X direction, perpendicular to wheel plane)
 *   - Left wheel  X     : -0.842
 *   - Right wheel X     :  0.843
 *   - Front axle  Z     : -1.285
 *   - Rear axle   Z     :  1.285
 */

import { writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dir = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dir, "../public/parts");

const PI2 = Math.PI * 2;

// ── Wheel layout (matches original OBJ) ──────────────────────────────────────
const WHEELS = [
  { label: "FL", cx: -0.842, cy: 0.40, cz: -1.285, side: -1 },
  { label: "FR", cx:  0.843, cy: 0.40, cz: -1.285, side:  1 },
  { label: "RL", cx: -0.842, cy: 0.40, cz:  1.285, side: -1 },
  { label: "RR", cx:  0.843, cy: 0.40, cz:  1.285, side:  1 },
];

// ── Rim dimensions ────────────────────────────────────────────────────────────
const OUTER_R  = 0.40;  // outer tire radius
const RIM_R    = 0.34;  // inner rim lip (spoke attaches here on outer rim ring)
const HUB_R    = 0.095; // hub center radius
const HALF_W   = 0.10;  // half wheel width in X
const SEGS     = 24;    // circle subdivisions

// ── Helpers ───────────────────────────────────────────────────────────────────

/** Return N [x,y,z] points forming a circle in YZ plane at given X/center. */
function circlePoints(x, cy, cz, r, n = SEGS) {
  const pts = [];
  for (let i = 0; i < n; i++) {
    const a = (PI2 * i) / n;
    pts.push([x, cy + r * Math.cos(a), cz + r * Math.sin(a)]);
  }
  return pts;
}

/**
 * Build OBJ string for all 4 wheels using a spoke-builder callback.
 *
 * @param {string} name - Label used in OBJ header
 * @param {Function} spokeFn - (ctx, cx, cy, cz, xo, xi, flip) => void
 *   ctx has: addVert, addFace, outerRingO, rimRingO, hubRingO, outerRingI
 */
function buildAllWheels(name, spokeFn) {
  const allVerts = [];
  const allFaces = [];

  for (const w of WHEELS) {
    const { cx, cy, cz, side } = w;
    // Outer face X (away from car body), inner face X (toward car body)
    const xo = cx - side * HALF_W;
    const xi = cx + side * HALF_W;
    // Faces need reversed winding for right-side wheels (side=+1)
    const flip = side === 1;

    const localVerts = [];
    const localFaces = [];

    function addVert(x, y, z) {
      localVerts.push([x, y, z]);
      return localVerts.length; // 1-indexed local
    }

    function addFace(...ids) {
      localFaces.push(flip ? [...ids].reverse() : ids);
    }

    function addRing(x, r, n = SEGS) {
      return circlePoints(x, cy, cz, r, n).map(([vx, vy, vz]) =>
        addVert(vx, vy, vz)
      );
    }

    // ── Base geometry ─────────────────────────────────────────────────────────
    const outerRingO = addRing(xo, OUTER_R);
    const outerRingI = addRing(xi, OUTER_R);
    const rimRingO   = addRing(xo, RIM_R);
    const hubRingO   = addRing(xo, HUB_R);
    const hubRingI   = addRing(xi, HUB_R);
    const centerO    = addVert(xo, cy, cz);
    const centerI    = addVert(xi, cy, cz);

    // Tire sidewall barrel
    for (let i = 0; i < SEGS; i++) {
      const j = (i + 1) % SEGS;
      addFace(outerRingO[i], outerRingI[i], outerRingI[j], outerRingO[j]);
    }

    // Outer rim ring face (annulus: outerR → rimR)
    for (let i = 0; i < SEGS; i++) {
      const j = (i + 1) % SEGS;
      addFace(outerRingO[i], outerRingO[j], rimRingO[j], rimRingO[i]);
    }

    // Hub cap outer
    for (let i = 0; i < SEGS; i++) {
      const j = (i + 1) % SEGS;
      addFace(centerO, hubRingO[i], hubRingO[j]);
    }

    // Hub cylinder barrel
    for (let i = 0; i < SEGS; i++) {
      const j = (i + 1) % SEGS;
      addFace(hubRingO[i], hubRingI[i], hubRingI[j], hubRingO[j]);
    }

    // Hub cap inner
    for (let i = 0; i < SEGS; i++) {
      const j = (i + 1) % SEGS;
      addFace(centerI, hubRingI[j], hubRingI[i]);
    }

    // ── Style-specific spokes ─────────────────────────────────────────────────
    spokeFn(
      { addVert, addFace, outerRingO, rimRingO, hubRingO, outerRingI, hubRingI },
      cx, cy, cz, xo, xi
    );

    // Accumulate into global arrays (offset vertex indices)
    const offset = allVerts.length;
    allVerts.push(...localVerts);
    allFaces.push(...localFaces.map((f) => f.map((i) => i + offset)));
  }

  // Build OBJ text
  const lines = [
    `# Chain Drift - ${name} wheel variant`,
    `# Generated by scripts/generate-wheel-variants.mjs`,
    `o Wheel_${name.replace(/\s+/g, "_")}`,
  ];
  for (const [x, y, z] of allVerts) {
    lines.push(`v ${x.toFixed(5)} ${y.toFixed(5)} ${z.toFixed(5)}`);
  }
  for (const face of allFaces) {
    lines.push(`f ${face.join(" ")}`);
  }
  return lines.join("\n") + "\n";
}

// ── Spoke styles ──────────────────────────────────────────────────────────────

/**
 * 5-Spoke: classic straight racing wheel.
 * Five rectangular spokes radiating from hub to rim.
 */
function spokes5Spoke({ addVert, addFace }, _cx, cy, cz, xo, xi) {
  const N_SPOKES   = 5;
  const HALF_ANGLE = 0.13; // angular half-width of each spoke (radians)

  for (let s = 0; s < N_SPOKES; s++) {
    const a = (PI2 * s) / N_SPOKES;

    const a0 = a - HALF_ANGLE;
    const a1 = a + HALF_ANGLE;

    // 4 outer-face vertices (at xo), 4 inner-face vertices (at xi)
    const ro0 = addVert(xo, cy + RIM_R * Math.cos(a0), cz + RIM_R * Math.sin(a0));
    const ro1 = addVert(xo, cy + RIM_R * Math.cos(a1), cz + RIM_R * Math.sin(a1));
    const ho0 = addVert(xo, cy + HUB_R * Math.cos(a0), cz + HUB_R * Math.sin(a0));
    const ho1 = addVert(xo, cy + HUB_R * Math.cos(a1), cz + HUB_R * Math.sin(a1));

    const ri0 = addVert(xi, cy + RIM_R * Math.cos(a0), cz + RIM_R * Math.sin(a0));
    const ri1 = addVert(xi, cy + RIM_R * Math.cos(a1), cz + RIM_R * Math.sin(a1));
    const hi0 = addVert(xi, cy + HUB_R * Math.cos(a0), cz + HUB_R * Math.sin(a0));
    const hi1 = addVert(xi, cy + HUB_R * Math.cos(a1), cz + HUB_R * Math.sin(a1));

    addFace(ho0, ro0, ro1, ho1);       // outer face
    addFace(hi0, hi1, ri1, ri0);       // inner face
    addFace(ro0, ri0, hi0, ho0);       // side A
    addFace(ro1, ho1, hi1, ri1);       // side B
  }
}

/**
 * Turbine: 5 curved blades offset at hub vs rim — directional, aggressive.
 */
function spokesTurbine({ addVert, addFace }, _cx, cy, cz, xo, xi) {
  const N_SPOKES   = 5;
  const TWIST      = 0.45; // how much the blade sweeps (radians)
  const BLADE_W    = 0.11; // half angular width of blade

  for (let s = 0; s < N_SPOKES; s++) {
    const aBase = (PI2 * s) / N_SPOKES;
    // Hub attachment centered at aBase, rim attachment shifted by TWIST
    const aHub = aBase;
    const aRim = aBase + TWIST;

    const ro0 = addVert(xo, cy + RIM_R * Math.cos(aRim - BLADE_W), cz + RIM_R * Math.sin(aRim - BLADE_W));
    const ro1 = addVert(xo, cy + RIM_R * Math.cos(aRim + BLADE_W), cz + RIM_R * Math.sin(aRim + BLADE_W));
    const ho0 = addVert(xo, cy + HUB_R * Math.cos(aHub - BLADE_W), cz + HUB_R * Math.sin(aHub - BLADE_W));
    const ho1 = addVert(xo, cy + HUB_R * Math.cos(aHub + BLADE_W), cz + HUB_R * Math.sin(aHub + BLADE_W));

    const ri0 = addVert(xi, cy + RIM_R * Math.cos(aRim - BLADE_W), cz + RIM_R * Math.sin(aRim - BLADE_W));
    const ri1 = addVert(xi, cy + RIM_R * Math.cos(aRim + BLADE_W), cz + RIM_R * Math.sin(aRim + BLADE_W));
    const hi0 = addVert(xi, cy + HUB_R * Math.cos(aHub - BLADE_W), cz + HUB_R * Math.sin(aHub - BLADE_W));
    const hi1 = addVert(xi, cy + HUB_R * Math.cos(aHub + BLADE_W), cz + HUB_R * Math.sin(aHub + BLADE_W));

    addFace(ho0, ro0, ro1, ho1);
    addFace(hi0, hi1, ri1, ri0);
    addFace(ro0, ri0, hi0, ho0);
    addFace(ro1, ho1, hi1, ri1);
  }
}

/**
 * Mesh: 10 primary spokes + 10 cross spokes at offset angles + mid-ring.
 * Dense lattice look.
 */
function spokesMesh({ addVert, addFace }, _cx, cy, cz, xo, xi) {
  const N_SPOKES = 10;
  const HALF_W   = 0.055;
  const MID_R    = (RIM_R + HUB_R) / 2 + 0.02;

  // Primary spokes (hub → rim)
  for (let s = 0; s < N_SPOKES; s++) {
    const a    = (PI2 * s) / N_SPOKES;
    const a0   = a - HALF_W;
    const a1   = a + HALF_W;

    const ro0 = addVert(xo, cy + RIM_R * Math.cos(a0), cz + RIM_R * Math.sin(a0));
    const ro1 = addVert(xo, cy + RIM_R * Math.cos(a1), cz + RIM_R * Math.sin(a1));
    const ho0 = addVert(xo, cy + HUB_R * Math.cos(a0), cz + HUB_R * Math.sin(a0));
    const ho1 = addVert(xo, cy + HUB_R * Math.cos(a1), cz + HUB_R * Math.sin(a1));
    const ri0 = addVert(xi, cy + RIM_R * Math.cos(a0), cz + RIM_R * Math.sin(a0));
    const ri1 = addVert(xi, cy + RIM_R * Math.cos(a1), cz + RIM_R * Math.sin(a1));
    const hi0 = addVert(xi, cy + HUB_R * Math.cos(a0), cz + HUB_R * Math.sin(a0));
    const hi1 = addVert(xi, cy + HUB_R * Math.cos(a1), cz + HUB_R * Math.sin(a1));

    addFace(ho0, ro0, ro1, ho1);
    addFace(hi0, hi1, ri1, ri0);
    addFace(ro0, ri0, hi0, ho0);
    addFace(ro1, ho1, hi1, ri1);
  }

  // Cross spokes (between primary spokes, rim → mid ring only)
  const HALF_WC = 0.04;
  for (let s = 0; s < N_SPOKES; s++) {
    const a  = (PI2 * (s + 0.5)) / N_SPOKES;
    const a0 = a - HALF_WC;
    const a1 = a + HALF_WC;

    const ro0 = addVert(xo, cy + RIM_R * Math.cos(a0), cz + RIM_R * Math.sin(a0));
    const ro1 = addVert(xo, cy + RIM_R * Math.cos(a1), cz + RIM_R * Math.sin(a1));
    const mo0 = addVert(xo, cy + MID_R * Math.cos(a0), cz + MID_R * Math.sin(a0));
    const mo1 = addVert(xo, cy + MID_R * Math.cos(a1), cz + MID_R * Math.sin(a1));
    const ri0 = addVert(xi, cy + RIM_R * Math.cos(a0), cz + RIM_R * Math.sin(a0));
    const ri1 = addVert(xi, cy + RIM_R * Math.cos(a1), cz + RIM_R * Math.sin(a1));
    const mi0 = addVert(xi, cy + MID_R * Math.cos(a0), cz + MID_R * Math.sin(a0));
    const mi1 = addVert(xi, cy + MID_R * Math.cos(a1), cz + MID_R * Math.sin(a1));

    addFace(mo0, ro0, ro1, mo1);
    addFace(mo0, mo1, ri1, ri0); // inner — note intentional swap
    addFace(ro0, ri0, mi0, mo0);
    addFace(ro1, mo1, mi1, ri1);
  }

  // Mid-ring barrel (thin structural ring connecting both faces)
  const midO = circlePoints(xo, cy, cz, MID_R).map(([x, y, z]) => addVert(x, y, z));
  const midI = circlePoints(xi, cy, cz, MID_R).map(([x, y, z]) => addVert(x, y, z));
  for (let i = 0; i < SEGS; i++) {
    const j = (i + 1) % SEGS;
    addFace(midO[i], midI[i], midI[j], midO[j]);
  }
}

// ── Generate files ─────────────────────────────────────────────────────────────
const VARIANTS = [
  { file: "Car_Wheels_5Spoke.obj",  label: "5Spoke",  fn: spokes5Spoke  },
  { file: "Car_Wheels_Turbine.obj", label: "Turbine",  fn: spokesTurbine },
  { file: "Car_Wheels_Mesh.obj",    label: "Mesh",     fn: spokesMesh    },
];

for (const { file, label, fn } of VARIANTS) {
  const content = buildAllWheels(label, fn);
  writeFileSync(join(OUT, file), content);
  const lines = content.split("\n").filter((l) => l.startsWith("v ")).length;
  console.log(`✓ ${file}  (${lines} vertices)`);
}

console.log("\nDone. Add these to src/data/carParts.ts to use them in game.");
